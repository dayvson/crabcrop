#!/usr/bin/env python3
"""Tests for scripts/check_locks.py.

Each case writes a Cargo.lock and a fuzz/Cargo.lock in the format cargo
writes into a throwaway directory and runs the check against it as CI
does; one case checks this repository's own lockfiles. Run directly:
python3 scripts/test_check_locks.py
"""
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

HERE = Path(__file__).resolve().parent
SCRIPT = HERE / "check_locks.py"
sys.path.insert(0, str(HERE))

import check_locks  # noqa: E402

REGISTRY = "registry+https://github.com/rust-lang/crates.io-index"

# A healthy root lock: one oxideav-h265 shared by crabcrop and
# oxideav-heif, the three splits SPLITS allows, and a duplicate that is
# no decoder.
ROOT_PACKAGES = [
    ("crabcrop", "0.10.0", None),
    ("image", "0.25.10", REGISTRY),
    ("miniz_oxide", "0.8.9", REGISTRY),
    ("miniz_oxide", "0.9.1", REGISTRY),
    ("moxcms", "0.8.1", REGISTRY),
    ("moxcms", "0.9.2", REGISTRY),
    ("oxideav-h265", "0.0.16", REGISTRY),
    ("oxideav-heif", "0.0.13", REGISTRY),
    ("roxmltree", "0.20.0", REGISTRY),
    ("roxmltree", "0.21.2", REGISTRY),
    ("syn", "1.0.109", REGISTRY),
    ("syn", "2.0.119", REGISTRY),
]
FUZZ_ONLY = [("crabcrop-fuzz", "0.0.0", None), ("libfuzzer-sys", "0.4.10", REGISTRY)]


def lock_text(packages):
    """A lockfile as cargo writes it, dependency lists and all."""
    out = [
        "# This file is automatically @generated by Cargo.",
        "# It is not intended for manual editing.",
        "version = 4",
    ]
    for name, version, source in sorted(packages):
        out += ["", "[[package]]", f'name = "{name}"', f'version = "{version}"']
        if source:
            out += [f'source = "{source}"', f'checksum = "{"ab" * 32}"']
        if name == "oxideav-heif":
            out += ["dependencies = [", ' "oxideav-core",', ' "oxideav-h265 0.0.16",', "]"]
    return "\n".join(out) + "\n"


class CheckLocks(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = Path(self.tmp.name)
        (self.root / "fuzz").mkdir()

    def tearDown(self):
        self.tmp.cleanup()

    def run_check(self, root_packages=ROOT_PACKAGES, fuzz_packages=None):
        if fuzz_packages is None:
            fuzz_packages = [*(root_packages or ROOT_PACKAGES), *FUZZ_ONLY]
        if root_packages is not None:
            (self.root / "Cargo.lock").write_text(lock_text(root_packages))
        (self.root / "fuzz/Cargo.lock").write_text(lock_text(fuzz_packages))
        done = subprocess.run(
            [sys.executable, str(SCRIPT), "--root", str(self.root)], capture_output=True, text=True
        )
        return done.returncode, done.stdout + done.stderr

    def assert_fails(self, expected, **locks):
        code, output = self.run_check(**locks)
        self.assertEqual(code, 1, output)
        for text in expected:
            self.assertIn(text, output)
        return output

    def test_this_repository_passes(self):
        # The lockfiles at issue #552 failed both rules: oxideav-h265 at
        # 0.0.15 and 0.0.16, and the fuzz lock a moxcms behind.
        found, problems = check_locks.check(check_locks.ROOT)
        self.assertEqual(problems, [])
        self.assertEqual(len(found["Cargo.lock"]["oxideav-h265"]), 1)

    def test_a_healthy_pair_passes(self):
        code, output = self.run_check()
        self.assertEqual(code, 0, output)
        self.assertIn("fuzz/Cargo.lock agrees with Cargo.lock", output)

    def test_two_hevc_decoders_fail(self):
        # The shape #494's lock refresh left: oxideav-heif on 0.0.15,
        # crabcrop's own pin on 0.0.16.
        packages = [*ROOT_PACKAGES, ("oxideav-h265", "0.0.15", REGISTRY)]
        self.assert_fails(
            [
                "Cargo.lock: oxideav-h265 (HEIC and HEVC) is locked at 2 versions (0.0.15, 0.0.16)",
                "cargo update -p oxideav-h265@0.0.15 --precise 0.0.16",
            ],
            root_packages=packages,
            fuzz_packages=[*packages, *FUZZ_ONLY],
        )

    def test_a_split_in_the_fuzz_lock_alone_fails(self):
        packages = [*ROOT_PACKAGES, ("png", "0.17.16", REGISTRY), ("png", "0.18.1", REGISTRY)]
        output = self.assert_fails(
            ["fuzz/Cargo.lock: png (PNG) is locked at 2 versions (0.17.16, 0.18.1)"],
            root_packages=[*ROOT_PACKAGES, ("png", "0.18.1", REGISTRY)],
            fuzz_packages=[*packages, *FUZZ_ONLY],
        )
        self.assertNotIn("\n  Cargo.lock: png", output)

    def test_every_oxideav_crate_counts_as_a_decoder(self):
        packages = [*ROOT_PACKAGES, ("oxideav-h267", "0.0.1", REGISTRY), ("oxideav-h267", "0.0.2", REGISTRY)]
        self.assert_fails(
            ["oxideav-h267 (HEIC and HEVC) is locked at 2 versions"],
            root_packages=packages,
            fuzz_packages=[*packages, *FUZZ_ONLY],
        )

    def test_a_duplicate_that_decodes_nothing_passes(self):
        packages = [*ROOT_PACKAGES, ("thiserror", "1.0.69", REGISTRY), ("thiserror", "2.0.21", REGISTRY)]
        code, output = self.run_check(root_packages=packages)
        self.assertEqual(code, 0, output)

    def test_versions_sort_by_number(self):
        packages = [*ROOT_PACKAGES, ("gif", "0.14.10", REGISTRY), ("gif", "0.14.9", REGISTRY)]
        self.assert_fails(
            ["gif (GIF) is locked at 2 versions (0.14.9, 0.14.10)", "-p gif@0.14.9 --precise 0.14.10"],
            root_packages=packages,
            fuzz_packages=[*packages, *FUZZ_ONLY],
        )

    def test_an_allowed_split_with_two_versions_in_one_line_fails(self):
        packages = [*ROOT_PACKAGES, ("moxcms", "0.9.1", REGISTRY)]
        self.assert_fails(
            ["moxcms (ICC profiles) has more than one version in a compatible line (0.8.1, 0.9.1, 0.9.2)"],
            root_packages=packages,
            fuzz_packages=[*packages, *FUZZ_ONLY],
        )

    def test_an_allowed_split_on_a_new_line_fails(self):
        packages = [p for p in ROOT_PACKAGES if p[:2] != ("moxcms", "0.9.2")] + [("moxcms", "0.10.0", REGISTRY)]
        self.assert_fails(
            ["moxcms (ICC profiles) is locked at 0.8.1, 0.10.0 (lines 0.8, 0.10), but SPLITS allows lines 0.8, 0.9"],
            root_packages=packages,
            fuzz_packages=[*packages, *FUZZ_ONLY],
        )

    def test_an_allowed_split_that_went_away_fails(self):
        packages = [p for p in ROOT_PACKAGES if p[:2] != ("roxmltree", "0.20.0")]
        self.assert_fails(
            ["roxmltree (SVG XML) is down to one version (0.21.2); remove its entry from SPLITS"],
            root_packages=packages,
            fuzz_packages=[*packages, *FUZZ_ONLY],
        )

    def test_a_drifted_fuzz_lock_fails(self):
        # The drift issue #552 found: the fuzz lock a moxcms release behind.
        fuzz = [p for p in ROOT_PACKAGES if p[:2] != ("moxcms", "0.9.2")] + [("moxcms", "0.9.1", REGISTRY)]
        self.assert_fails(
            [
                "fuzz/Cargo.lock has moxcms 0.8.1, 0.9.1, Cargo.lock has 0.8.1, 0.9.2",
                "cp Cargo.lock fuzz/Cargo.lock && cargo update -w --manifest-path fuzz/Cargo.toml",
            ],
            fuzz_packages=[*fuzz, *FUZZ_ONLY],
        )

    def test_a_shared_package_from_another_source_fails(self):
        fork = "git+https://example.invalid/syn?rev=abc#abc"
        fuzz = [p for p in ROOT_PACKAGES if p[:2] != ("syn", "2.0.119")] + [("syn", "2.0.119", fork)]
        self.assert_fails(["fuzz/Cargo.lock has syn"], fuzz_packages=[*fuzz, *FUZZ_ONLY])

    def test_a_path_package_version_is_compared(self):
        fuzz = [p for p in ROOT_PACKAGES if p[0] != "crabcrop"] + [("crabcrop", "0.9.11", None)]
        self.assert_fails(
            ["fuzz/Cargo.lock has crabcrop 0.9.11 (path), Cargo.lock has 0.10.0 (path)"],
            fuzz_packages=[*fuzz, *FUZZ_ONLY],
        )

    def test_packages_one_lock_alone_carries_are_not_compared(self):
        root = [*ROOT_PACKAGES, ("tempfile", "3.20.0", REGISTRY)]
        code, output = self.run_check(root_packages=root, fuzz_packages=[*ROOT_PACKAGES, *FUZZ_ONLY])
        self.assertEqual(code, 0, output)

    def test_a_missing_lockfile_fails(self):
        self.assert_fails(["Cargo.lock: cannot read it"], root_packages=None)

    def test_compatible_lines(self):
        cases = {"1.4.2": "1", "0.9.2": "0.9", "0.10.0": "0.10", "0.0.16": "0.0.16", "2.0.0-rc.15": "2"}
        for version, line in cases.items():
            with self.subTest(version=version):
                self.assertEqual(check_locks.compatible_line(version), line)

    def test_every_allowed_split_says_why(self):
        for name, (lines, reason) in check_locks.SPLITS.items():
            with self.subTest(name=name):
                self.assertTrue(check_locks.decoder_label(name), f"{name} is in SPLITS but is no decoder")
                self.assertGreaterEqual(len(lines), 2)
                self.assertGreater(len(reason), 40)


if __name__ == "__main__":
    unittest.main()
