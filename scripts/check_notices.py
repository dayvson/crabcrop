def listed_crates(text):
    """The (name, version) rows of the file's crate table."""
    lines = text.split("\n")
    try:
        start = lines.index(TABLE_HEADER) + 2
    except ValueError:
        return None
    listed = set()
    for line in lines[start:]:
        found = re.match(r"^\| (\S+) \| (\S+) \| .* \|$", line)
        if not found:
            break
        listed.add((found.group(1), found.group(2)))
    return listed


def built_crates(root, release, offline, runner):
    """The (name, version) of every crate the release build compiles, from
    cargo tree: normal and build dependencies, for each dist target, with
    dist's features. The workspace's own packages are left out."""
    targets, features = release
    built = set()
    for target in targets:
        cmd = [cargo(), "tree", "--locked", "--color", "never", "--manifest-path", str(root / "Cargo.toml")]
        cmd += ["--target", target, "-e", "normal,build", "--prefix", "none", "-f", "{p}"]
        if features:
            cmd += ["--features", ",".join(features)]
        if offline:
            cmd.append("--offline")
        code, out, err = runner(cmd, root)
        if code != 0:
            raise NoticeError(f"cargo tree --target {target} failed:\n{tail(err)}")
        for line in out.splitlines():
            found = re.match(r"^(\S+) v(\S+)(.*)$", line.strip())
            if found and not re.search(r" \((/|[A-Za-z]:\\)", found.group(3)):
                built.add((found.group(1), found.group(2)))
    return built


def crate_problems(listed, built):
    """What the crate table gets wrong, one line per crate name."""
    added, gone = built - listed, listed - built
    problems = []
    for name in sorted({n for n, _ in added | gone}):
        new = ", ".join(v for n, v in sorted(added) if n == name)
        old = ", ".join(v for n, v in sorted(gone) if n == name)
        if new and old:
            problems.append(f"the release build compiles {name} {new}, and {NOTICES} lists {name} {old}")
        elif new:
            problems.append(f"the release build compiles {name} {new}, which {NOTICES} does not list")
        else:
            problems.append(f"{NOTICES} lists {name} {old}, which the release build no longer compiles")
    return problems


def pin_problems(root, parts):
    problems = []
    for part in parts:
        if not (isinstance(part, Directive) and part.kind == "pinned"):
            continue
        path = part.one("file")
        try:
            text = read_text(root / path)
        except (OSError, UnicodeDecodeError) as err:
            problems.append(f"{TEMPLATE}:{part.line}: cannot read {path}: {err}")
            continue
        for digest in part.args.get("sha256", []):
            if digest not in text:
                problems.append(
                    f"{path} no longer pins the download with sha256 {digest}, which the texts {TEMPLATE} copies "
                    f"after line {part.line} come from: copy them again from the download it pins now, then update "
                    "that line"
                )
    return problems


def shipping_problems(root):
    problems = []
    try:
        include = quoted_list(read_text(root / DIST), "include", DIST)
    except (OSError, UnicodeDecodeError, NoticeError):
        include = []
    if NOTICES not in include:
        problems.append(f"{DIST}: `include` does not name {NOTICES}, so the release tarballs would not carry it")
    try:
        formula = read_text(root / FORMULA)
    except (OSError, UnicodeDecodeError):
        formula = ""
    if FORMULA_INSTALL not in formula:
        problems.append(f"{FORMULA}: the formula does not `{FORMULA_INSTALL}`, so a Homebrew install would not carry it")
    return problems


def first_difference(old, new):
    diff = list(difflib.unified_diff(old.split("\n"), new.split("\n"), NOTICES, "regenerated", n=1, lineterm=""))
    return "\n".join("  " + line for line in diff[:24]) + ("\n  ..." if len(diff) > 24 else "")


def check(root, strict=False, offline=False, regenerate=True, runner=run_command):
    """(problems, notes) for the notices file in the checkout at root."""
    problems, notes, stale = [], [], []
    try:
        text = read_text(root / NOTICES)
    except (OSError, UnicodeDecodeError) as err:
        return [f"{NOTICES}: cannot read it ({err}): run python3 scripts/check_notices.py --write"], notes
    try:
        release = read_release(root)
        template = read_text(root / TEMPLATE)
        parts = parse_template(template)
        inputs = inputs_digest(root, release, template, parts)
    except (OSError, UnicodeDecodeError, NoticeError) as err:
        return [str(err)], notes

    stamp = STAMP.search(text)
    if not stamp:
        stale.append(f"{NOTICES}: no generator stamp: it was not written by scripts/check_notices.py --write")
    else:
        if stamp.group(1) != CARGO_ABOUT_VERSION:
            stale.append(f"{NOTICES} was generated with cargo-about {stamp.group(1)}, not {CARGO_ABOUT_VERSION}")
        if stamp.group(2) != inputs:
            stale.append(
                f"{CONFIG}, {TEMPLATE}, a file it copies, or dist's targets or features changed since "
                f"{NOTICES} was generated"
            )
        if stamp.group(3) != body_digest(text, stamp.group(0)):
            stale.append(f"{NOTICES} was edited by hand: it is generated, so change {TEMPLATE} or {CONFIG} instead")
    problems += pin_problems(root, parts)
    problems += shipping_problems(root)

    listed = listed_crates(text)
    if listed is None:
        stale.append(f"{NOTICES}: no crate table (a `{TABLE_HEADER}` line)")
    else:
        try:
            stale += crate_problems(listed, built_crates(root, release, offline, runner))
        except NoticeError as err:
            problems.append(str(err))

    if regenerate:
        tool, version = find_cargo_about(runner)
        if tool is None:
            (problems if strict else notes).append(f"not regenerated: {version}")
        else:
            try:
                fresh = generate(root, tool, release, offline, runner)
            except (OSError, UnicodeDecodeError, NoticeError) as err:
                problems.append(str(err))
            else:
                if fresh != text:
                    stale.append(
                        f"{NOTICES} is not what cargo-about {version} generates now:\n{first_difference(text, fresh)}"
                    )
                else:
                    notes.append(f"regenerated with cargo-about {version}: unchanged")
    if stale:
        stale.append(f"regenerate it with python3 scripts/check_notices.py --write (cargo-about {CARGO_ABOUT_VERSION}: {INSTALL})")
    return stale + problems, notes


def main(argv=None, runner=run_command):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true", help=f"regenerate {NOTICES}")
    parser.add_argument("--strict", action="store_true", help=f"fail when cargo-about {CARGO_ABOUT_VERSION} is missing")
    parser.add_argument("--offline", action="store_true", help="read only crates cargo has already downloaded")
    parser.add_argument("--root", type=Path, default=ROOT, help="repository checkout to check")
    args = parser.parse_args(argv)
    root = args.root.resolve()

    if args.write:
        tool, version = find_cargo_about(runner)
        if tool is None:
            print(f"check_notices: {version}", file=sys.stderr)
            return 1
        try:
            text = generate(root, tool, read_release(root), args.offline, runner)
        except (OSError, UnicodeDecodeError, NoticeError) as err:
            print(f"check_notices: {err}", file=sys.stderr)
            return 1
        (root / NOTICES).write_text(text, encoding="utf-8")
        print(f"wrote {NOTICES} with cargo-about {version}")

    problems, notes = check(root, args.strict, args.offline, regenerate=not args.write, runner=runner)
    if problems:
        print("third-party notices check failed:", file=sys.stderr)
        for problem in problems:
            print(f"  {problem}", file=sys.stderr)
        return 1
    count = len(listed_crates(read_text(root / NOTICES)) or ())
    targets, features = read_release(root)
    print(
        f"{NOTICES} lists the {count} crates the release build compiles ({len(targets)} targets, features: "
        f"{', '.join(features) or 'default'}), and every artifact ships it"
        + "".join(f"; {note}" for note in notes)
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
