#!/usr/bin/env python3
"""Keep THIRD-PARTY-NOTICES.md in step with what the release ships.

The release tarballs, the container images and the Homebrew install carry
a crabcrop binary with the code of every crate the release build compiles,
and of the C libraries some of those crates vendor. THIRD-PARTY-NOTICES.md
holds their license notices (issue #682). It is generated, never edited:

  python3 scripts/check_notices.py --write

That runs cargo-about (CARGO_ABOUT_VERSION exactly: INSTALL installs it)
over Cargo.lock, for the features and targets dist-workspace.toml builds,
with the accepted licenses and clarifications in scripts/notices/about.toml,
and renders what it finds into scripts/notices/template.md. The template is
the hand-written part: the native libraries, whose license texts it copies
from the sources the crates vendor (pinned by SHA-256, so a changed text
stops the generator until someone has read it) or from the copies under
scripts/notices/ of the downloads the build pins. cargo-about refuses a
crate whose license the accepted list does not satisfy, and the script
refuses an accepted license no crate needs any more.

With no flag, the script checks the file:

  crates   The crates the release build compiles (cargo tree, for each dist
           target, with dist's features) are the crates the file lists, at
           the versions it lists.
  inputs   about.toml, the template, the files it copies and dist's targets
           and features are the ones the file was generated from.
  edited   The file is what the generator wrote.
  pins     Every download the template's copies came from is still the one
           its file pins (dav1d's tarball in scripts/build_dav1d.sh, ONNX
           Runtime's in Dockerfile.ai).
  ships    dist's include puts the file in the tarballs, and the Homebrew
           formula installs it. tests/deploy_recipes.rs checks the images.
  fresh    With cargo-about CARGO_ABOUT_VERSION installed: regenerating writes
           exactly the file, and no crate's license is one about.toml does
           not accept. --strict, which CI passes, fails when it is missing.

Usage: python3 scripts/check_notices.py [--write] [--strict] [--offline] [--root DIR]

--offline keeps cargo off the network: it reads only crates already in its
cache. CI runs --strict in rust.yml's notices job; the release preflight
and scripts/test_all.sh run the check without it, and the gate runs its
tests (scripts/test_check_notices.py). RELEASING.md has the details.
"""
import argparse
import difflib
import hashlib
import json
import os
import re
import shlex
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NOTICES = "THIRD-PARTY-NOTICES.md"
CONFIG = "scripts/notices/about.toml"
TEMPLATE = "scripts/notices/template.md"
DIST = "dist-workspace.toml"
FORMULA = "scripts/release_formula.py"
FORMULA_INSTALL = 'doc.install "THIRD-PARTY-NOTICES.md"'

# The generator. A cargo-about release can change what it detects, so the
# version is exact, and moving it regenerates the file in the same change.
# The CI mirror (docs/rust-workflow.yml) installs the same version.
CARGO_ABOUT_VERSION = "0.9.3"
INSTALL = f"cargo install --locked --features cli cargo-about@{CARGO_ABOUT_VERSION}"
CRATES_IO = "registry+https://github.com/rust-lang/crates.io-index"

# Licenses whose binary distribution must point the recipients at the
# source code of the files they cover: the file says where, per crate.
SOURCE_OFFERS = {"MPL-2.0"}

TABLE_HEADER = "| Crate | Version | License | Used under |"
DIRECTIVE = re.compile(r"^<!-- (stamp|include|copyrights|pinned|crates|source-offers|notice-files|licenses)(?:: (.*?))? -->$")
STAMP = re.compile(
    r"^<!-- Generated by scripts/check_notices\.py with cargo-about (\S+); do not edit it by hand "
    r"\(RELEASING\.md says how to regenerate it\)\. inputs sha256:([0-9a-f]{64}) body sha256:([0-9a-f]{64}) -->$",
    re.M,
)
NOTICE_FILE = re.compile(r"^NOTICE(\.(txt|md))?$", re.I)
COPYRIGHT_LINE = re.compile(r"^[\s;*/#!-]*(Copyright\b.*?)\s*$")


class NoticeError(Exception):
    """A problem that stops the generator; the message says what to do."""


def run_command(cmd, cwd):
    """Run cmd, returning (exit code, stdout, stderr). Tests swap it out."""
    try:
        done = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    except OSError as err:
        return 127, "", f"cannot run {cmd[0]}: {err}"
    return done.returncode, done.stdout, done.stderr


def read_text(path):
    """A text file as the generator reads it: UTF-8, LF line ends, no BOM."""
    return path.read_bytes().decode("utf-8").replace("\r\n", "\n").lstrip("\ufeff")


def sha256(text):
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def quoted_list(text, key, where):
    """The strings of a one-line TOML array `key = ["a", "b"]`."""
    found = re.search(rf'^{re.escape(key)} = \[(.*?)\]', text, re.M | re.S)
    if not found:
        raise NoticeError(f"{where}: no `{key} = [...]` line")
    return re.findall(r'"([^"]*)"', found.group(1))


def read_release(root):
    """The targets and features dist builds the release binaries with."""
    try:
        text = read_text(root / DIST)
    except (OSError, UnicodeDecodeError) as err:
        raise NoticeError(f"{DIST}: cannot read it: {err}") from err
    targets = sorted(quoted_list(text, "targets", DIST))
    if not targets:
        raise NoticeError(f"{DIST}: `targets` names no target")
    features = sorted(quoted_list(text, "features", DIST))
    return targets, features


# ---------------------------------------------------------------- template


# The keys each directive takes. In a `from` or `to` value, \n is a line break.
DIRECTIVE_KEYS = {
    "include": {"crate", "path", "file", "label", "from", "to", "uncomment", "sha256"},
    "copyrights": {"crate", "glob"},
    "pinned": {"file", "sha256"},
}


class Directive:
    """One `<!-- kind: key=value ... -->` line of the template."""

    def __init__(self, kind, args, line):
        self.kind = kind
        self.line = line
        self.args = {}
        for word in shlex.split(args or ""):
            key, sep, value = word.partition("=")
            if not sep:
                raise NoticeError(f"{TEMPLATE}:{line}: `{word}` is not key=value")
            if key not in DIRECTIVE_KEYS.get(kind, set()):
                raise NoticeError(f"{TEMPLATE}:{line}: the {kind} directive takes no {key}=")
            self.args.setdefault(key, []).append(value.replace("\\n", "\n"))
        if kind == "include" and ("crate" in self.args) == ("file" in self.args):
            raise NoticeError(f"{TEMPLATE}:{line}: an include names either crate= and path=, or file= and label=")

    def one(self, key, default=None):
        values = self.args.get(key)
        if values is None:
            if default is None:
                raise NoticeError(f"{TEMPLATE}:{self.line}: the {self.kind} directive needs {key}=")
            return default
        if len(values) > 1:
            raise NoticeError(f"{TEMPLATE}:{self.line}: {key}= appears {len(values)} times")
        return values[0]


def parse_template(text):
    """The template's lines, each a string or a Directive."""
    parts = []
    for number, line in enumerate(text.split("\n"), 1):
        found = DIRECTIVE.match(line)
        if found:
            parts.append(Directive(found.group(1), found.group(2), number))
        elif re.match(r"^<!-- [a-z-]+(:| -->)", line):
            raise NoticeError(f"{TEMPLATE}:{number}: unknown directive {line!r}")
        else:
            parts.append(line)
    kinds = [p.kind for p in parts if isinstance(p, Directive)]
    for kind in ("stamp", "crates", "licenses"):
        if kinds.count(kind) != 1:
            raise NoticeError(f"{TEMPLATE}: needs exactly one `<!-- {kind} -->` line, found {kinds.count(kind)}")
    return parts


def repo_file_inputs(root, parts):
    """The repository files the template copies, as {path: text}."""
    files = {}
    for part in parts:
        if isinstance(part, Directive) and part.kind == "include" and "file" in part.args:
            path = part.one("file")
            try:
                files[path] = read_text(root / path)
            except (OSError, UnicodeDecodeError) as err:
                raise NoticeError(f"{TEMPLATE}:{part.line}: cannot read {path}: {err}") from err
    return files


def inputs_digest(root, release, template, parts):
    """One digest over everything the file is generated from besides the
    crates: the configuration, the template and the files it copies, dist's
    targets and features, and the generator's version."""
    targets, features = release
    inputs = [
        ("about.toml", read_text(root / CONFIG)),
        ("template.md", template),
        ("release", f"targets={','.join(targets)};features={','.join(features)}"),
        ("cargo-about", CARGO_ABOUT_VERSION),
    ]
    inputs += sorted(repo_file_inputs(root, parts).items())
    digest = hashlib.sha256()
    for name, text in inputs:
        data = text.encode("utf-8")
        digest.update(f"{name}\0{len(data)}\0".encode() + data)
    return digest.hexdigest()


def body_digest(text, stamp):
    return sha256(text.replace(stamp, "<!-- stamp -->", 1))


def stamp_line(inputs, body):
    return (
        f"<!-- Generated by scripts/check_notices.py with cargo-about {CARGO_ABOUT_VERSION}; do not edit it by hand "
        f"(RELEASING.md says how to regenerate it). inputs sha256:{inputs} body sha256:{body} -->"
    )


# ---------------------------------------------------------------- rendering


def fence(text, info="text"):
    """`text` in a code fence no line of it can close."""
    longest = max((len(run) for run in re.findall(r"`+", text)), default=0)
    ticks = "`" * max(3, longest + 1)
    return f"{ticks}{info}\n{text.rstrip(chr(10))}\n{ticks}"


def and_list(items):
    items = list(items)
    if len(items) < 2:
        return "".join(items)
    return f"{', '.join(items[:-1])} and {items[-1]}"


def crate_label(key):
    return f"{key[0]} {key[1]}"


class Model:
    """cargo-about's findings, the workspace's own crates left out."""

    def __init__(self, data):
        self.crates = {}
        for entry in data.get("crates", []):
            package = entry["package"]
            if not package.get("source"):
                continue
            key = (package["name"], package["version"])
            self.crates[key] = {
                "license": " ".join(str(entry["license"]).split()),
                "source": package["source"],
                "repository": package.get("repository"),
                "root": Path(package["manifest_path"]).parent,
                "used": set(),
            }
        self.licenses = []
        for license in data.get("licenses", []):
            users = sorted(
                {(u["crate"]["name"], u["crate"]["version"]) for u in license["used_by"] if u["crate"].get("source")}
            )
            if not users:
                continue
            for key in users:
                if key not in self.crates:
                    raise NoticeError(f"cargo-about names {crate_label(key)} under {license['id']} but not among the crates")
                self.crates[key]["used"].add(license["id"])
            self.licenses.append(
                {
                    "id": license["id"],
                    "name": license["name"],
                    "text": license["text"].replace("\r\n", "\n").lstrip("\ufeff"),
                    "source": self.source_label(license.get("source_path"), users),
                    "users": users,
                }
            )
        bare = [crate_label(k) for k, c in sorted(self.crates.items()) if not c["used"]]
        if bare:
            raise NoticeError(f"cargo-about reproduced no license text for {and_list(bare)}")
        self.licenses.sort(key=lambda lic: (lic["id"], lic["users"], lic["text"]))

    def source_label(self, path, users):
        """Where a license text came from, for the reader."""
        if not path:
            return None
        path = Path(path)
        for key in users:
            root = self.crates[key]["root"]
            if not path.is_absolute():
                return f"`{path.as_posix()}` in {crate_label(key)}"
            try:
                return f"`{path.relative_to(root).as_posix()}` in {crate_label(key)}"
            except ValueError:
                continue
        return f"`{path.name}`"

    def crate(self, name, line):
        """The one version of `name` the release build compiles."""
        found = [key for key in self.crates if key[0] == name]
        if len(found) != 1:
            versions = ", ".join(k[1] for k in sorted(found)) or "none"
            raise NoticeError(
                f"{TEMPLATE}:{line}: the release build compiles {name} at {len(found)} versions ({versions}); "
                "the directive needs exactly one"
            )
        return found[0], self.crates[found[0]]


def excerpt(text, directive, where):
    start_mark = directive.args.get("from", [None])[0]
    end_mark = directive.args.get("to", [None])[0]
    start = 0
    if start_mark is not None:
        start = text.find(start_mark)
        if start < 0:
            raise NoticeError(f"{TEMPLATE}:{directive.line}: {where} has no {start_mark!r}")
    end = len(text)
    if end_mark is not None:
        end = text.find(end_mark, start)
        if end < 0:
            raise NoticeError(f"{TEMPLATE}:{directive.line}: {where} has no {end_mark!r} after its start")
        end += len(end_mark)
    return text[start:end]


def uncomment(text, prefix):
    lines = []
    for line in text.split("\n"):
        if line.startswith(prefix):
            line = line[len(prefix) :]
            if line.startswith(" "):
                line = line[1:]
        lines.append(line)
    return "\n".join(lines)


def render_include(root, directive, model):
    if "crate" in directive.args:
        key, crate = model.crate(directive.one("crate"), directive.line)
        path = directive.one("path")
        source = crate["root"] / path
        label = f"`{path}` in {crate_label(key)}"
    else:
        path = directive.one("file")
        source = root / path
        label = directive.one("label")
    try:
        text = read_text(source)
    except (OSError, UnicodeDecodeError) as err:
        raise NoticeError(f"{TEMPLATE}:{directive.line}: cannot read {label}: {err}") from err
    part = excerpt(text, directive, label)
    pinned = directive.one("sha256")
    if sha256(part) != pinned:
        raise NoticeError(
            f"{TEMPLATE}:{directive.line}: the text of {label} has changed (sha256 {sha256(part)}, the template pins "
            f"{pinned}): read the new text, check what it asks of a binary distribution, then pin its sha256"
        )
    if "uncomment" in directive.args:
        part = uncomment(part, directive.one("uncomment"))
    return f"From {label}:\n\n{fence(part)}"


def glob_regex(pattern):
    out = ""
    i = 0
    while i < len(pattern):
        if pattern.startswith("**/", i):
            out += "(?:.*/)?"
            i += 3
        elif pattern[i] == "*":
            out += "[^/]*"
            i += 1
        elif pattern[i] == "?":
            out += "[^/]"
            i += 1
        else:
            out += re.escape(pattern[i])
            i += 1
    return re.compile(out + r"\Z")


def render_copyrights(directive, model):
    key, crate = model.crate(directive.one("crate"), directive.line)
    patterns = directive.args.get("glob") or []
    if not patterns:
        raise NoticeError(f"{TEMPLATE}:{directive.line}: the copyrights directive needs glob=")
    regexes = [glob_regex(p) for p in patterns]
    root = crate["root"]
    lines = set()
    matched = 0
    for folder, dirs, files in os.walk(root):
        dirs.sort()
        for name in sorted(files):
            path = Path(folder) / name
            rel = path.relative_to(root).as_posix()
            if not any(r.match(rel) for r in regexes):
                continue
            matched += 1
            try:
                text = read_text(path)
            except (OSError, UnicodeDecodeError) as err:
                raise NoticeError(f"{TEMPLATE}:{directive.line}: cannot read {rel} in {crate_label(key)}: {err}") from err
            for line in text.split("\n"):
                found = COPYRIGHT_LINE.match(line)
                if found:
                    lines.add(found.group(1))
    if not lines:
        raise NoticeError(
            f"{TEMPLATE}:{directive.line}: no copyright line in the {matched} files of {crate_label(key)} "
            f"that {', '.join(patterns)} match"
        )
    where = ", ".join(f"`{p}`" for p in patterns)
    return f"From the {where} files of {crate_label(key)}:\n\n{fence(chr(10).join(sorted(lines)))}"


def render_crates(model, release):
    targets, features = release
    feature_text = f"with the {and_list(f'`{f}`' for f in features)} feature{'s' if len(features) > 1 else ''}"
    if not features:
        feature_text = "with the default features"
    rows = [TABLE_HEADER, "| --- | --- | --- | --- |"]
    for key, crate in sorted(model.crates.items()):
        rows.append(f"| {key[0]} | {key[1]} | {crate['license']} | {', '.join(sorted(crate['used']))} |")
    return (
        f"The release binaries are built {feature_text} for {and_list(f'`{t}`' for t in targets)}. "
        f"That build compiles these {len(model.crates)} crates, build dependencies and procedural macros "
        "included. *License* is the license a crate declares; *used under* names the licenses whose texts "
        "the [license texts](#license-texts) reproduce for it, one of them where the crate offers a choice.\n\n"
        + "\n".join(rows)
    )


def render_source_offers(model):
    offers = []
    for key, crate in sorted(model.crates.items()):
        licenses = sorted(crate["used"] & SOURCE_OFFERS)
        if not licenses:
            continue
        if crate["source"] != CRATES_IO:
            raise NoticeError(
                f"{crate_label(key)} is used under {', '.join(licenses)} from {crate['source']}, not crates.io: "
                "say where its source code is available, by hand, in the template"
            )
        line = f"- {crate_label(key)} ({', '.join(licenses)}): https://crates.io/api/v1/crates/{key[0]}/{key[1]}/download"
        if crate["repository"]:
            line += f" (its repository: {crate['repository']})"
        offers.append(line)
    if not offers:
        return ""
    return (
        "### Source code\n\n"
        "The licenses of these crates ask that the source code of the files they cover stay available to everyone "
        "who receives the binary. The binary carries them unmodified, and their source code is the package "
        "crates.io publishes, which crates.io keeps for every published version:\n\n" + "\n".join(offers)
    )


def render_notice_files(model):
    blocks = []
    for key, crate in sorted(model.crates.items()):
        try:
            names = sorted(n for n in os.listdir(crate["root"]) if NOTICE_FILE.match(n))
        except OSError as err:
            raise NoticeError(f"cannot list {crate_label(key)}'s files at {crate['root']}: {err}") from err
        for name in names:
            try:
                text = read_text(crate["root"] / name)
            except (OSError, UnicodeDecodeError) as err:
                raise NoticeError(f"cannot read {name} in {crate_label(key)}: {err}") from err
            blocks.append(f"From `{name}` in {crate_label(key)}:\n\n{fence(text)}")
    if not blocks:
        return ""
    return (
        "### NOTICE files\n\n"
        "The Apache License 2.0 asks that the attribution notices in a work's NOTICE file go with it. "
        "The NOTICE files at the crates' roots:\n\n" + "\n\n".join(blocks)
    )


def render_licenses(model):
    sections = []
    ids = sorted({lic["id"] for lic in model.licenses})
    for license_id in ids:
        texts = [lic for lic in model.licenses if lic["id"] == license_id]
        crates = {key for lic in texts for key in lic["users"]}
        blocks = [
            f"### {texts[0]['name']} ({license_id})",
            f"{len(crates)} crate{'s' if len(crates) != 1 else ''}, "
            f"{len(texts)} text{'s' if len(texts) != 1 else ''}.",
        ]
        for lic in texts:
            users = and_list(crate_label(k) for k in lic["users"])
            if lic["source"]:
                lead = f"Used by {users}. From {lic['source']}:"
            else:
                lead = f"Used by {users}, which ship no copy of the license; this is its standard text:"
            blocks.append(f"{lead}\n\n{fence(lic['text'])}")
        sections.append("\n\n".join(blocks))
    return "\n\n".join(sections)


def render(root, parts, model, release):
    """The notices file, with a placeholder where the stamp goes. A
    directive with nothing to show drops out with the blank line after it;
    rendered text is never reflowed."""
    renderers = {
        "stamp": lambda part: "<!-- stamp -->",
        "include": lambda part: render_include(root, part, model),
        "copyrights": lambda part: render_copyrights(part, model),
        "pinned": lambda part: "",
        "crates": lambda part: render_crates(model, release),
        "source-offers": lambda part: render_source_offers(model),
        "notice-files": lambda part: render_notice_files(model),
        "licenses": lambda part: render_licenses(model),
    }
    out = []
    dropped = False
    for part in parts:
        block = renderers[part.kind](part) if isinstance(part, Directive) else part
        if block == "" and (dropped or isinstance(part, Directive)):
            dropped = isinstance(part, Directive)
            continue
        dropped = False
        out.append(block)
    return "\n".join(out).rstrip("\n") + "\n"


# ---------------------------------------------------------------- cargo-about


def cargo():
    return os.environ.get("CARGO", "cargo")


def find_cargo_about(runner):
    """(path, version) of the cargo-about to run, or (None, why not)."""
    tool = os.environ.get("CARGO_ABOUT") or shutil.which("cargo-about")
    if not tool:
        return None, f"cargo-about {CARGO_ABOUT_VERSION} is not installed ({INSTALL})"
    code, out, err = runner([tool, "--version"], ROOT)
    words = out.split()
    version = words[1] if code == 0 and len(words) == 2 and words[0] == "cargo-about" else None
    if version != CARGO_ABOUT_VERSION:
        found = version or (out + err).strip() or f"exit {code}"
        return None, f"{tool} is cargo-about {found}, and the notices are generated with {CARGO_ABOUT_VERSION} ({INSTALL})"
    return tool, version


def cargo_about_findings(root, tool, release, offline, runner):
    """cargo-about's JSON for the release build. It runs with --frozen, so
    it reads only crates cargo has downloaded and never fetches a license
    file from a repository: the output depends on Cargo.lock alone."""
    targets, features = release
    if not offline:
        code, _, err = runner([cargo(), "fetch", "--locked", "--color", "never", "--manifest-path", str(root / "Cargo.toml")], root)
        if code != 0:
            raise NoticeError(f"cargo fetch failed:\n{tail(err)}")
    cmd = [tool, "--color", "never", "generate", "--format", "json", "--frozen", "--fail"]
    for feature in features:
        cmd += ["--features", feature]
    for target in targets:
        cmd += ["--target", target]
    cmd += ["-c", str(root / CONFIG), "--manifest-path", str(root / "Cargo.toml")]
    code, out, err = runner(cmd, root)
    err = re.sub(r"\x1b\[[0-9;]*m", "", err)
    if code != 0:
        hint = ""
        if "failed to satisfy license requirements" in err:
            hint = (
                f"\na crate's license is not one {CONFIG} accepts: read what it asks of a binary distribution, "
                "then accept it there with its reason, or drop the crate"
            )
        raise NoticeError(f"cargo-about failed:\n{tail(err)}{hint}")
    complaints = [line for line in err.splitlines() if re.search(r"\[(WARN|ERROR)\]|^(warning|error)(\[\w+\])?:", line)]
    if complaints:
        raise NoticeError(
            "cargo-about warned, and the notices take no warning (a clarification in "
            f"{CONFIG} that no longer applies, or one for a crate the build dropped):\n" + tail("\n".join(complaints))
        )
    try:
        return json.loads(out)
    except ValueError as err:
        raise NoticeError(f"cargo-about printed no JSON: {err}") from err


def tail(text, lines=30):
    kept = text.strip().splitlines()
    return "\n".join(("  " + line) for line in kept[-lines:])


def unused_accepted(root, model):
    """Accepted licenses no crate of the release build needs."""
    accepted = quoted_list(read_text(root / CONFIG), "accepted", CONFIG)
    used = {lic["id"] for lic in model.licenses}
    declared = [crate["license"] for crate in model.crates.values()]
    unused = []
    for entry in accepted:
        if " WITH " in entry:
            needed = any(entry in expression for expression in declared)
        else:
            needed = entry in used
        if not needed:
            unused.append(entry)
    return unused


def generate(root, tool, release, offline=False, runner=run_command):
    """The notices file, as the generator writes it now."""
    template = read_text(root / TEMPLATE)
    parts = parse_template(template)
    model = Model(cargo_about_findings(root, tool, release, offline, runner))
    unused = unused_accepted(root, model)
    if unused:
        raise NoticeError(
            f"{CONFIG} accepts {and_list(unused)}, which no crate in the release build needs: remove "
            f"{'it' if len(unused) == 1 else 'them'}, so a crate that brings {'it' if len(unused) == 1 else 'one'} "
            "back is reviewed again"
        )
    text = render(root, parts, model, release)
    inputs = inputs_digest(root, release, template, parts)
    return text.replace("<!-- stamp -->", stamp_line(inputs, sha256(text)), 1)


