#!/usr/bin/env python3
"""Keep one JavaScript implementation of the URL grammar (issue #482).

The grammar's JavaScript implementation is the TypeScript SDK's
explainer, sdks/typescript/src/explain.ts; the SDK's typed builders
import its checks. The playground is a static page with no build step,
so it serves the SDK's build of that module from playground/sdk/, and
this script puts it there:

    python3 scripts/sync_playground_sdk.py          # refresh playground/sdk/
    python3 scripts/sync_playground_sdk.py --check  # fail on drift or a copy

Both build the SDK first (npm run build in sdks/typescript, which needs
`npm ci` there once), then read dist/explain.js and every module it
imports. The copies are the build output byte for byte behind a
generated-file header. --check changes nothing and fails when:

- a file in playground/sdk/ differs from the fresh build, is missing,
  or is left over from an older build (a grammar change that was not
  synced, or a hand edit);
- a JavaScript or TypeScript source anywhere else defines the grammar
  again: a function named like one of the explainer's, one of the
  explainer's own messages, or the class-name charset. Tests are not
  scanned: they quote the explainer's messages to check them.

The copy scan reads names and text only, so a copy renamed and reworded
throughout gets past it. It catches a paste or a lightly edited one;
the corpus tests (every surface against spec/operation-vectors.json and
spec/explain-verdicts.json) catch a copy that behaves differently.

scripts/test_all.sh runs --check; scripts/test_sync_playground_sdk.py
tests this script.
"""
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SDK = "sdks/typescript"
ENTRY = "explain.js"
TARGET = "playground/sdk"

# The one place the grammar is written by hand, and its synced build.
HOME = "sdks/typescript/src/explain.ts"

HEADER = (
    "// Generated by scripts/sync_playground_sdk.py from {sdk}/dist/{name},\n"
    "// the TypeScript SDK's build of {sdk}/src/{stem}.ts. Do not edit:\n"
    "// change the SDK and run the script again.\n"
)

# What a second copy of the grammar looks like: the explainer's own
# function names, messages only it prints, and the class-name charset
# (in either property-name spelling).
GRAMMAR_FUNCTIONS = (
    "validateFilter",
    "explainFilters",
    "explainSegment",
    "parseObjectsAlign",
    "parseSizeSegment",
    "isSizeShaped",
)
MARKERS = [
    re.compile(r"\bfunction\s*\*?\s*(?:%s)\b" % "|".join(GRAMMAR_FUNCTIONS)),
    re.compile(r"\b(?:const|let|var)\s+(?:%s)\s*=" % "|".join(GRAMMAR_FUNCTIONS)),
    re.compile(r"\b(?:%s)\s*\([^)]*\)\s*(?::[^{]*)?\{" % "|".join(GRAMMAR_FUNCTIONS)),
    re.compile(r"the server rejects this filter"),
    re.compile(r"no signature segment: the path is a single segment"),
    re.compile(r"expiry overflows the server's u64 parser"),
    re.compile(r"unsupported debug view"),
    re.compile(r"\\p\{(?:L|Letter)\}\\p\{(?:N|Number)\}"),
]
SOURCE_SUFFIXES = {
    ".js", ".mjs", ".cjs", ".ts", ".mts", ".cts", ".tsx", ".jsx",
    ".vue", ".svelte", ".astro", ".html",
}
SKIP_DIRS = {
    ".git", "node_modules", "dist", "target", ".work", ".nuxt", ".output",
    ".svelte-kit", ".astro", ".next", "test", "tests", "__pycache__",
}

# A static import or re-export: `import "x"`, or an import or export
# clause (names, braces, `*`, `as`) followed by `from "x"`.
IMPORT = re.compile(
    r"""^(?:import|export)\s+(?:[\w$*\s{},]*?\s*from\s*)?["']([^"']+)["']""", re.M
)


class SyncError(Exception):
    pass


def build_sdk(root):
    sdk = root / SDK
    if not (sdk / "node_modules").is_dir():
        raise SyncError(f"{SDK} has no node_modules: run `npm ci` there first")
    run = subprocess.run(["npm", "run", "build"], cwd=sdk, capture_output=True, text=True)
    if run.returncode != 0:
        raise SyncError(f"`npm run build` failed in {SDK}:\n{run.stdout}{run.stderr}")


def expected_files(root):
    """{name: content} for playground/sdk/: dist/explain.js and every
    module it imports, each behind the generated-file header."""
    dist = root / SDK / "dist"
    out = {}
    pending = [ENTRY]
    while pending:
        name = pending.pop()
        if name in out:
            continue
        path = dist / name
        if not path.is_file():
            raise SyncError(f"{SDK}/dist/{name} is missing: build the SDK (npm run build in {SDK})")
        text = path.read_text(encoding="utf-8")
        for spec in IMPORT.findall(text):
            if not spec.startswith("./") or "/" in spec[2:] or not spec.endswith(".js"):
                raise SyncError(
                    f"{SDK}/dist/{name} imports {spec!r}; the static playground can only "
                    "load sibling modules, so the explainer must import nothing else"
                )
            pending.append(spec[2:])
        stem = name[: -len(".js")]
        out[name] = HEADER.format(sdk=SDK, name=name, stem=stem) + text
    return out


def sync(root, check):
    """Write (or, with check, compare) playground/sdk/. Returns the
    problems found; empty means in sync."""
    want = expected_files(root)
    target = root / TARGET
    have = {p.name for p in target.iterdir() if p.is_file()} if target.is_dir() else set()
    problems = []
    for name, content in sorted(want.items()):
        path = target / name
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == content:
            continue
        if check:
            state = "is missing" if current is None else "differs from the SDK's build"
            problems.append(f"{TARGET}/{name} {state}")
        else:
            target.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    for name in sorted(have - set(want)):
        if check:
            problems.append(f"{TARGET}/{name} is not part of the SDK's explainer build")
        else:
            (target / name).unlink()
    return problems


def grammar_copies(root):
    """Sources outside explain.ts (and its synced build) that define the
    grammar again, as "path:line: text" strings."""
    allowed = {HOME} | {f"{TARGET}/{name}" for name in expected_names(root)}
    found = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
        for filename in sorted(filenames):
            path = Path(dirpath) / filename
            if path.suffix not in SOURCE_SUFFIXES or ".test." in filename:
                continue
            rel = path.relative_to(root).as_posix()
            if rel in allowed:
                continue
            try:
                text = path.read_text(encoding="utf-8")
            except (UnicodeDecodeError, OSError):
                continue
            for number, line in enumerate(text.splitlines(), 1):
                if any(marker.search(line) for marker in MARKERS):
                    found.append(f"{rel}:{number}: {line.strip()}")
    return found


def expected_names(root):
    """The synced file names, from playground/sdk/ itself, so the copy
    scan does not need a build to know which files are the build."""
    target = root / TARGET
    return [p.name for p in target.iterdir() if p.is_file()] if target.is_dir() else []


def main(argv):
    check = "--check" in argv[1:]
    unknown = [a for a in argv[1:] if a != "--check"]
    if unknown:
        print(f"usage: {argv[0]} [--check]", file=sys.stderr)
        return 2
    try:
        build_sdk(ROOT)
        problems = sync(ROOT, check)
    except SyncError as e:
        print(f"sync_playground_sdk: {e}", file=sys.stderr)
        return 1
    copies = grammar_copies(ROOT)
    for problem in problems:
        print(f"{problem}; run python3 scripts/sync_playground_sdk.py", file=sys.stderr)
    for copy in copies:
        print(
            f"{copy}\n  a second JavaScript copy of the URL grammar: import it from "
            f"{HOME} (the SDK) instead (issue #482)",
            file=sys.stderr,
        )
    if problems or copies:
        return 1
    if check:
        print(f"{TARGET}/ matches the SDK's explainer build, and the grammar has one JavaScript copy")
    else:
        print(f"{TARGET}/ refreshed from the SDK's explainer build")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
