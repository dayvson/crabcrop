#!/usr/bin/env python3
"""Tests for scripts/sync_playground_sdk.py.

Each case lays out a small tree (an SDK build, a playground, a framework
file) in a fresh temporary directory and runs the script's sync and copy
scan against it, so no build runs here. The last case scans the real
repository. Run directly: python3 scripts/test_sync_playground_sdk.py
"""
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import sync_playground_sdk as sps  # noqa: E402

EXPLAIN_JS = 'import { MAX_DIMENSION } from "./limits.js";\nexport function explainUrl() {}\n'
LIMITS_JS = "export const MAX_DIMENSION = 16383;\n"
EXPLAIN_TS = (
    'import { MAX_DIMENSION } from "./limits.ts";\n'
    "function validateFilter(name: string, args: string | null): string | null {\n"
    "  return `the server rejects this filter: ${name}`;\n"
    "}\n"
)
COPY = "function validateFilter(name, args) {\n  return null;\n}\n"


class Tree:
    def __init__(self, root):
        self.root = Path(root)
        self.write("sdks/typescript/dist/explain.js", EXPLAIN_JS)
        self.write("sdks/typescript/dist/limits.js", LIMITS_JS)
        self.write("sdks/typescript/src/explain.ts", EXPLAIN_TS)
        self.write("playground/lib.mjs", 'export { explainUrl } from "./sdk/explain.js";\n')

    def write(self, rel, text):
        path = self.root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")

    def read(self, rel):
        return (self.root / rel).read_text(encoding="utf-8")


class SyncTest(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory(prefix="sync-playground-sdk-")
        self.addCleanup(self._tmp.cleanup)
        self.tree = Tree(self._tmp.name)
        self.root = self.tree.root

    def test_sync_writes_the_build_and_its_imports_behind_a_header(self):
        self.assertEqual(sps.sync(self.root, check=True), [
            "playground/sdk/explain.js is missing",
            "playground/sdk/limits.js is missing",
        ])
        self.assertEqual(sps.sync(self.root, check=False), [])
        explain = self.tree.read("playground/sdk/explain.js")
        self.assertTrue(explain.startswith("// Generated by scripts/sync_playground_sdk.py"))
        self.assertTrue(explain.endswith(EXPLAIN_JS))
        self.assertTrue(self.tree.read("playground/sdk/limits.js").endswith(LIMITS_JS))
        self.assertEqual(sps.sync(self.root, check=True), [])
        self.assertEqual(sps.grammar_copies(self.root), [])

    def test_check_reports_a_stale_or_edited_copy(self):
        sps.sync(self.root, check=False)
        self.tree.write("sdks/typescript/dist/limits.js", "export const MAX_DIMENSION = 16384;\n")
        self.assertEqual(sps.sync(self.root, check=True), [
            "playground/sdk/limits.js differs from the SDK's build",
        ])
        sps.sync(self.root, check=False)
        edited = self.tree.read("playground/sdk/explain.js") + "// a hand edit\n"
        self.tree.write("playground/sdk/explain.js", edited)
        self.assertEqual(sps.sync(self.root, check=True), [
            "playground/sdk/explain.js differs from the SDK's build",
        ])

    def test_check_reports_a_file_the_build_no_longer_has(self):
        sps.sync(self.root, check=False)
        self.tree.write("playground/sdk/old.js", "export {};\n")
        self.assertEqual(sps.sync(self.root, check=True), [
            "playground/sdk/old.js is not part of the SDK's explainer build",
        ])
        sps.sync(self.root, check=False)
        self.assertFalse((self.root / "playground/sdk/old.js").exists())

    def test_an_import_the_static_page_cannot_load_is_refused(self):
        for spec in ("#crypto", "node:crypto", "../index.js", "./nested/x.js"):
            self.tree.write("sdks/typescript/dist/explain.js", f'import {{ x }} from "{spec}";\n')
            with self.assertRaisesRegex(sps.SyncError, "can only load sibling modules"):
                sps.sync(self.root, check=True)

    def test_a_missing_build_says_to_build(self):
        (self.root / "sdks/typescript/dist/explain.js").unlink()
        with self.assertRaisesRegex(sps.SyncError, "build the SDK"):
            sps.sync(self.root, check=True)

    def test_a_second_copy_of_the_grammar_is_found(self):
        sps.sync(self.root, check=False)
        self.tree.write("playground/lib.mjs", COPY)
        self.tree.write("frameworks/nuxt/crabcrop.ts", "const isSizeShaped = (seg: string) => false;\n")
        self.tree.write("frameworks/astro/x.astro", "<script>const re = /^[\\p{L}\\p{N} _.\\-/]+$/u;</script>\n")
        self.tree.write("sdks/mcp/src/index.ts", "const table = {\n  explainSegment(seg) {\n  },\n};\n")
        self.tree.write("sdks/typescript/src/operations.ts", 'throw new Error("the server rejects this filter");\n')
        self.assertEqual(sps.grammar_copies(self.root), [
            "frameworks/astro/x.astro:1: <script>const re = /^[\\p{L}\\p{N} _.\\-/]+$/u;</script>",
            "frameworks/nuxt/crabcrop.ts:1: const isSizeShaped = (seg: string) => false;",
            "playground/lib.mjs:1: function validateFilter(name, args) {",
            "sdks/mcp/src/index.ts:2: explainSegment(seg) {",
            'sdks/typescript/src/operations.ts:1: throw new Error("the server rejects this filter");',
        ])

    def test_calls_tests_builds_and_dependencies_are_not_copies(self):
        sps.sync(self.root, check=False)
        self.tree.write("playground/app.mjs", "if (explainSegment(seg)) {\n  render(validateFilter(a, b));\n}\n")
        self.tree.write("playground/test/lib.test.mjs", 'assert.match(e, /the server rejects this filter/);\n')
        self.tree.write("sdks/typescript/test/x.test.ts", COPY)
        self.tree.write("frameworks/nuxt/node_modules/pkg/index.js", COPY)
        self.tree.write("tests/browser-bundles/.work/sdk/dist/bundle.js", COPY)
        self.tree.write("sdks/typescript/dist/explain.js", EXPLAIN_JS + COPY)
        self.assertEqual(sps.grammar_copies(self.root), [])

    def test_the_repository_has_one_javascript_grammar(self):
        self.assertEqual(sps.grammar_copies(sps.ROOT), [])
        self.assertTrue((sps.ROOT / sps.HOME).is_file())
        self.assertTrue((sps.ROOT / sps.TARGET / "explain.js").is_file())


if __name__ == "__main__":
    unittest.main()
